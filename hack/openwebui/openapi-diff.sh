#!/usr/bin/env bash
# Compare the routes the provider uses between two OpenAPI snapshots and write the report
# docs/api-notes/openapi-diff.md. The routes, the change each one is expected to show and its
# classification come from docs/api-notes/provider-routes.tsv. The script fails when a route's
# change differs from the expected one, so a new change cannot slip in under an old
# classification; after reviewing it, OPENAPI_DIFF_ACCEPT=1 records the new change in the table
# (the classification and rationale still need updating by hand).
# Usage: mise run owui:openapi-diff [from-version] [to-version]   (default 0.11.4 0.12.4)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
repo_root="$(cd "$here/../.." && pwd)"
from="${1:-0.11.4}"
to="${2:-0.12.4}"
routes="$repo_root/docs/api-notes/provider-routes.tsv"
out="$repo_root/docs/api-notes/openapi-diff.md"
snapshot() { echo "$repo_root/docs/api-notes/openapi/v$1.json"; }

operation() { # <version> <method> <path>
  jq -cS --arg method "$2" --arg path "$3" -f "$here/openapi-operation.jq" "$(snapshot "$1")"
}

# changes <a> <b> summarizes how two resolved operations differ: each difference is reported at
# the shallowest node that exists on one side only (+ added in <b>, - removed), or as a changed
# value (~), with schema plumbing (properties, anyOf, items, indexes) left out of the names.
changes() {
  jq -rn --argjson a "$1" --argjson b "$2" '
    def leaves: paths(type != "object" and type != "array");
    def name: map(select(type == "string" and (IN("properties", "anyOf", "items", "allOf", "oneOf") | not))) | join(".");
    def first_missing($p): first(range(1; ($p | length) + 1) as $n | $p[0:$n] as $q
      | select((($a | getpath($q)) == null) != (($b | getpath($q)) == null)) | $q);
    [($a | leaves), ($b | leaves)] | unique
    | map(. as $p | select(($a | getpath($p)) != ($b | getpath($p))))
    | map(. as $p | (first_missing($p) // null) as $m
          | if $m == null then "~" + ($p | name)
            elif ($a | getpath($m)) == null then "+" + ($m | name)
            else "-" + ($m | name) end)
    | unique | .[]'
}

stale=0
rows=""
table="resource	method	path	class	expected	rationale"$'\n'
while IFS= read -r line; do
  # cut keeps empty fields, which `read` with a tab IFS would collapse.
  resource="$(cut -f1 <<<"$line")" method="$(cut -f2 <<<"$line")" path="$(cut -f3 <<<"$line")"
  class="$(cut -f4 <<<"$line")" expected="$(cut -f5 <<<"$line")" rationale="$(cut -f6 <<<"$line")"
  [[ "$resource" == resource ]] && continue
  a="$(operation "$from" "$method" "$path")"
  b="$(operation "$to" "$method" "$path")"
  if [[ "$a" == null || "$b" == null ]]; then
    change="missing in $([[ "$a" == null ]] && echo "$from" || echo "$to")"
  elif [[ "$a" == "$b" ]]; then
    change="unchanged"
  else
    change="$(changes "$a" "$b" | paste -sd ' ' -)"
  fi
  if [[ "$change" != "$expected" ]]; then
    echo "unreviewed change: ${method^^} $path: expected '$expected', got '$change'" >&2
    stale=1
  fi
  if [[ "$class" == none && "$change" != unchanged && -z "$rationale" ]]; then
    echo "unexplained change: ${method^^} $path is classified 'none' without a rationale" >&2
    stale=1
  fi
  table+="$resource"$'\t'"$method"$'\t'"$path"$'\t'"$class"$'\t'"$change"$'\t'"$rationale"$'\n'
  # shellcheck disable=SC2016 # the backticks are literal Markdown, not a command substitution
  shown="$(tr ' ' '\n' <<<"$change" | sed 's/^[+~-].*/`&`/' | paste -sd ' ' -)"
  rows+="| $resource | \`${method^^} $path\` | $shown | **$class** | $rationale |"$'\n'
done <"$routes"

if [[ "${OPENAPI_DIFF_ACCEPT:-}" == 1 ]]; then
  printf '%s' "$table" >"$routes"
  echo "recorded the current changes in ${routes#"$repo_root/"}; review the classifications" >&2
  stale=0
fi

{
  echo "# OpenAPI diff: $from → $to, routes used by the provider"
  echo
  echo "Generated by \`mise run owui:openapi-diff\` (\`hack/openwebui/openapi-diff.sh\`) from \`openapi/v$from.json\` and \`openapi/v$to.json\`; do not edit by hand."
  echo "The routes and their classification live in [\`provider-routes.tsv\`](provider-routes.tsv)."
  echo
  echo "Each operation is compared on its parameters, request body and 200 response, with every \`\$ref\` inlined; summaries, descriptions, titles and operation ids are ignored. *Change* lists the schema paths that differ."
  echo
  echo "Classification: **none** (nothing the provider sends or reads changed; a changed route says why), **profile** (absorbable by a version profile in the client layer), **breaking** (needs a spec or design change). *Change*: \`+\` added in $to, \`-\` removed, \`~\` changed value. Behavior that changed without a schema change (status codes, defaults) is not visible here; it is classified in ADR-0001."
  echo
  echo "| Resource | Route | Change | Class | Why |"
  echo "| --- | --- | --- | --- | --- |"
  printf '%s' "$rows"
} >"$out"
echo "wrote ${out#"$repo_root/"}"
exit "$stale"
